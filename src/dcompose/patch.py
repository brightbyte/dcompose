"""Render the difference between a config and its fixed copy as a compose override file.

Compose merges override lists by appending and cannot drop a key by omitting
it, so removals use the `!reset` tag and replaced lists use `!override`.
Values are written as JSON, which is valid YAML.
"""

import json

from dcompose.text import SAFE_YAML_KEY, printable

HEADER = "# Generated by `dcompose fix`. Save as compose.override.yaml, or load it last with -f."


def render(original, fixed, unfixed=()):
    lines = [HEADER]
    lines += [f"# edit: {printable(note)}" for note in mount_notes(original, fixed)]
    lines += [f"# not fixed: {printable(problem)}" for problem in unfixed]

    changes = service_changes(original, fixed)
    if any("user" in service for service in changes.values()):
        lines.append("# note: dcompose sets DCOMPOSE_UID and DCOMPOSE_GID; plain docker compose needs them exported.")
    if not changes:
        return "\n".join([*lines, "services: {}", ""])

    lines.append("services:")
    for name, service in changes.items():
        lines.append(f"  {json.dumps(name)}:")
        lines += [f"    {yaml_key(key)}: {value}" for key, value in service.items()]
    return "\n".join([*lines, ""])


def yaml_key(key):
    return key if SAFE_YAML_KEY.match(key) else json.dumps(key)


def mount_notes(original, fixed):
    """One note per mount whose source was replaced by a placeholder."""
    notes = []
    for name, before in original.get("services", {}).items():
        after = fixed["services"][name]
        for old, new in zip(before.get("volumes", []), after.get("volumes", [])):
            if old.get("source") != new.get("source"):
                notes.append(
                    f"service {name}: mount source {old['source']} was replaced by the placeholder "
                    f"{new['source']}, which compose creates empty; point it at a path inside the project")
    return notes


def service_changes(original, fixed):
    """Map service name to {key: rendered YAML value} for the keys that differ."""
    changes = {}
    for name, before in original.get("services", {}).items():
        after = fixed["services"][name]
        service = {
            key: render_value(after[key] if key in after else None)
            for key in sorted(set(before) | set(after))
            if before.get(key) != after.get(key)
        }
        if service:
            changes[name] = service
    return changes


def render_value(value):
    if value is None:
        return "!reset null"
    if isinstance(value, list):
        return "!override " + json.dumps(value)
    return json.dumps(value)
